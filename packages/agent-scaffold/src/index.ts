import { existsSync, realpathSync } from "node:fs";
import { access, mkdir, open } from "node:fs/promises";
import { dirname, isAbsolute, relative, resolve, sep } from "node:path";

export type ArtifactKind = "agent" | "skill";
export async function scaffold(
  root: string,
  kind: ArtifactKind,
  name: string,
  description: string,
) {
  if (!/^[a-z][a-z0-9-]{0,62}$/.test(name)) throw new Error("Use a lowercase artifact name.");
  if (!description.trim() || description.length > 1024)
    throw new Error("Provide a concise description.");
  if (kind !== "agent" && kind !== "skill") throw new Error("Expected agent or skill.");
  const canonical =
    kind === "agent" ? `.agent-config/agents/${name}.md` : `.agent-config/skills/${name}/SKILL.md`;
  const override = kind === "agent" ? `.local/agents/${name}.md` : `.local/skills/${name}/SKILL.md`;
  const frontmatter = `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n`;
  const pointer = `If \`${override}\` exists, read and follow that file.\nOtherwise read and follow \`${canonical}\`.\n\nDo not edit this file directly. Put repo-specific overrides in \`.local/${kind}s/\`.\n`;
  const files: Record<string, string> = {
    [canonical]: `${frontmatter}\n# ${name}\n\n## Purpose\n\n## Inputs\n\n## Procedure\n\n## Boundaries\n\n## Output\n`,
  };
  for (const prefix of ["", "static-references/"]) {
    if (kind === "skill") {
      for (const harness of [".claude", ".github", ".agents"])
        files[`${prefix}${harness}/skills/${name}/SKILL.md`] =
          `${frontmatter}<!-- agent-config-managed: skill-reference -->\n${pointer}`;
    } else {
      for (const [harness, suffix] of [
        [".claude", ".md"],
        [".github", ".agent.md"],
      ])
        files[`${prefix}${harness}/agents/${name}${suffix}`] =
          `${frontmatter}<!-- agent-config-managed: agent-reference -->\n${pointer}`;
      files[`${prefix}.codex/agents/${name}.toml`] =
        `# agent-config-managed: codex-agent-reference\nname = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(description)}\ndeveloper_instructions = ${JSON.stringify(pointer)}\n`;
    }
  }
  const base = realpathSync(root);
  for (const path of Object.keys(files)) {
    let parent = dirname(resolve(base, path));
    while (!existsSync(parent)) parent = dirname(parent);
    const rel = relative(base, realpathSync(parent));
    if (isAbsolute(rel) || rel === ".." || rel.startsWith(`..${sep}`))
      throw new Error("Reference parent escapes the artifact root");
  }
  // Check every collision before creating the first file.
  for (const path of Object.keys(files)) {
    try {
      await access(resolve(root, path));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") continue;
      throw error;
    }
    throw new Error(`Refusing to replace ${path}`);
  }
  for (const [path, content] of Object.entries(files)) {
    const target = resolve(root, path);
    await mkdir(dirname(target), { recursive: true });
    const file = await open(target, "wx");
    try {
      await file.writeFile(content);
    } finally {
      await file.close();
    }
  }
  return { canonical, files: Object.keys(files) };
}
